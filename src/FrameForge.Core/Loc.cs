    public static AppLanguage Language { get; private set; } = AppLanguage.English;

    public static event Action? Changed;

    public static AppLanguage FromCulture()
    {
        string name = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
        if (name.Equals("ru", StringComparison.OrdinalIgnoreCase))
            return AppLanguage.Russian;
        if (name.Equals("de", StringComparison.OrdinalIgnoreCase))
            return AppLanguage.German;
        return AppLanguage.English;
    }

    public static void Set(AppLanguage language)
    {
        if (!Enum.IsDefined(language))
            language = AppLanguage.English;
        if (Language == language)
            return;

        Language = language;
        Changed?.Invoke();
    }

    public static string Get(string key)
    {
        Dictionary<string, string> table = Language switch
        {
            AppLanguage.German => De,
            AppLanguage.Russian => Ru,
            _ => En
        };
        return table.TryGetValue(key, out string? value) ? value : key;
    }

    public static string Format(string key, params object?[] args) =>
        string.Format(CultureInfo.CurrentCulture, Get(key), args);
